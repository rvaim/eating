export type StickerTranslationKey = keyof typeof zh
export const stickerTranslations = { 'zh-CN': zh, 'en-US': en }
registerTranslations('stickers', stickerTranslations)
export const st = (key: StickerTranslationKey, params?: TranslationParams) => translate('stickers', key, params)
export function stickerError(error: unknown): string {
  const code = error && typeof error === 'object' && 'code' in error ? String(error.code) : ''
  if (code === 'INVALID_HOST_RESPONSE') return st('error.invalidResponse')
  if (code === 'REQUEST_INTERRUPTED' || code === 'REQUEST_CANCELLED') return st('error.interrupted')
  const key = `error.${code}` as StickerTranslationKey
  return Object.hasOwn(zh, key) ? st(key) : st('error.generic')
}
