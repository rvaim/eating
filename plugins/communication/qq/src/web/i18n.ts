export const qqTranslations = { 'zh-CN': zhCN, 'en-US': enUS }
registerTranslations('qq', qqTranslations)

function resourceText(key: string, fallback: string, params?: TranslationParams): string {
  return Object.hasOwn(zhCN, key) ? translate('qq', key, params) : fallback
}

export function toolTitle(tool: PluginToolDefinition): string {
  return resourceText(`tool.${tool.name}.title`, tool.title)
}
export function toolDescription(tool: PluginToolDefinition): string {
  return resourceText(`tool.${tool.name}.description`, tool.description)
}
export function parameterLabel(tool: PluginToolDefinition | undefined, key: string, schema: JsonObject = {}): string {
  const fallback = typeof schema.title === 'string' ? schema.title : key
  return tool && Object.hasOwn(zhCN, `tool.${tool.name}.title`)
    ? resourceText(`tool.${tool.name}.parameter.${key}.label`, resourceText(`parameter.${key}.label`, fallback)) : fallback
}
export function parameterDescription(tool: PluginToolDefinition | undefined, key: string, schema: JsonObject, params?: TranslationParams): string {
  const fallback = typeof schema.description === 'string' ? schema.description : key
  return tool && Object.hasOwn(zhCN, `tool.${tool.name}.title`)
    ? resourceText(`tool.${tool.name}.parameter.${key}.description`, resourceText(`parameter.${key}.description`, fallback, params), params) : fallback
}
export function parameterOptionLabel(tool: PluginToolDefinition | undefined, key: string, value: string): string {
  return tool && Object.hasOwn(zhCN, `tool.${tool.name}.title`) ? resourceText(`option.${key}.${value}`, value) : value
}
export function toolSchemaHelp(tool: PluginToolDefinition): string {
  return Object.hasOwn(zhCN, `tool.${tool.name}.title`) ? resourceText(`tool.${tool.name}.schemaHelp`, translate('qq', 'tests.schemaHelp'))
    : typeof tool.inputSchema.description === 'string' ? tool.inputSchema.description : ''
}
export function capabilityTitle(capability: PluginCapability): string {
  return resourceText(`tool.${capability.id}.title`, resourceText(`capability.${capability.id}.title`, capability.name))
}
export function capabilityDescription(capability: PluginCapability): string {
  return resourceText(`tool.${capability.id}.description`, resourceText(`capability.${capability.id}.description`, capability.description))
}
